import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { PROWESS_DEFINITION_KINDS, compileAbilityConstruction, createProwessDefinitionBundle } from "@prowess/game";
import { createRulesetContext } from "@prowess/rules";
import { AFFINITY_CONTENT, CONSTRUCTION_DEFINITIONS, characterOf, maneuverComposition, spellComposition } from "../fixtures/m5-wo5-construction-catalog";

/**
 * M5-WO5 — the construction plans that the existing POST /api/rules/evaluate endpoint and Rules Inspector are
 * regression-tested with (apps/studio/tests/integration/m5-wo5-construction-api.test.ts): one VALID Spell (Arcane
 * Expert, 2 Effects, 1 Casting Condition, Signature 1 of 4 used) and one INVALID Maneuver (Martial Trained, 2 Effects
 * against a capacity of 1). This test REGENERATES them from the canonical content and the real compiler and requires
 * the committed fixture to be identical. Set M5_WO5_WRITE_FIXTURE=1 to rewrite it deliberately.
 */
const ROOT = path.resolve(import.meta.dirname, "../../../..");
const FIXTURE = path.join(ROOT, "apps/studio/tests/integration/fixtures/m5-wo5-construction-plans.json");
const uuid = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const RULESET = uuid(9801);
const MANIFEST = uuid(9802);
const KEYWORDS = AFFINITY_CONTENT.keywords.map((k, i) => ({ keywordId: uuid(9950 + i), canonicalKey: k.canonicalKey, categoryId: uuid(9949) }));

function bundle() {
  const identity = (i: number) => ({ entityId: uuid(10000 + i), entityVersionId: uuid(10500 + i) });
  const rules = CONSTRUCTION_DEFINITIONS.map((d, i) => ({ ...identity(i), canonicalKey: d.canonicalKey, entityType: PROWESS_DEFINITION_KINDS[d.definitionKind].entityTypes[0], sourceRulesetId: RULESET, sourceManifestId: MANIFEST }));
  const ruleset = createRulesetContext({ rulesetId: RULESET, manifestId: MANIFEST, rules });
  if (!ruleset.ok) throw new Error("ruleset");
  const definitions = CONSTRUCTION_DEFINITIONS.map((d, i) => ({
    schemaVersion: d.schemaVersion,
    systemFamily: PROWESS_DEFINITION_KINDS[d.definitionKind].family,
    definitionKind: d.definitionKind,
    ...identity(i),
    canonicalKey: d.canonicalKey,
    payload: d.payload,
    provenance: { rulesetId: RULESET, manifestId: MANIFEST, releaseId: null, sourceRulesetId: RULESET, sourceManifestId: MANIFEST, legacyTerms: [] },
  }));
  const out = createProwessDefinitionBundle({ ruleset: ruleset.value, definitions });
  if (!out.ok) throw new Error(JSON.stringify(out.problems));
  return { ruleset: ruleset.value, bundle: out.value };
}

function build() {
  const { ruleset, bundle: definitions } = bundle();
  const ref = (canonicalKey: string) => {
    const d = definitions.definitions.find((x) => x.canonicalKey === canonicalKey)!;
    return { entityId: d.entityId, entityVersionId: d.entityVersionId, canonicalKey: d.canonicalKey, definitionKind: d.definitionKind, systemFamily: d.systemFamily };
  };
  const compile = (subjectKey: string, composition: Record<string, unknown>, skills: Record<string, string>, usedSlots: number) => {
    const plan = compileAbilityConstruction({ contractVersion: 1, subjectKey, composition, definitions, ruleset, character: characterOf(skills), keywords: KEYWORDS, signature: { usedSlots, candidate: { slotUse: "DEFAULT" } } });
    if (!plan.ok) throw new Error(JSON.stringify(plan.problems));
    return plan.value;
  };
  const valid = compile("inspector_spell", spellComposition(ref, ["spell.effect.direct_damage", "spell.effect.healing"], ["spell.casting_condition.verbal"]), { "skill.arcana": "EXPERT" }, 1);
  const invalid = compile("inspector_maneuver", maneuverComposition(ref, ["maneuver.effect.strike", "maneuver.effect.sweep"]), { "skill.martial": "TRAINED" }, 0);
  return JSON.parse(
    JSON.stringify({
      note: "GENERATED by packages/prowess-db/tests/unit/m5-wo5-inspector-fixture.test.ts from the canonical construction content and @prowess/game — do not edit by hand.",
      valid: { evaluationKey: "m5-wo5.construction-valid", plan: valid.evaluationPlan, outputs: valid.outputs, sourceMap: valid.sourceMap },
      invalid: { evaluationKey: "m5-wo5.construction-invalid", plan: invalid.evaluationPlan, outputs: invalid.outputs, sourceMap: invalid.sourceMap },
    }),
  ) as Record<string, unknown>;
}

describe("M5-WO5 Rules Inspector / API fixture is exactly what @prowess/game compiles", () => {
  it("regenerates identically (deterministic compilation of canonical construction content)", () => {
    const fresh = build();
    if (process.env.M5_WO5_WRITE_FIXTURE === "1") writeFileSync(FIXTURE, `${JSON.stringify(fresh, null, 2)}\n`);
    expect(JSON.parse(readFileSync(FIXTURE, "utf8"))).toEqual(fresh);
    expect(build()).toEqual(fresh);
  });
});
