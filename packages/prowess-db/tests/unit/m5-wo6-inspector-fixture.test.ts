import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { PROWESS_DEFINITION_KINDS, compileAbilityTargeting, createProwessDefinitionBundle } from "@prowess/game";
import { createRulesetContext } from "@prowess/rules";
import { KEYWORD_CONTENT, TARGETING_DEFINITIONS, characterOf, maneuverWith, spellWith } from "../fixtures/m5-wo6-targeting-catalog";

/**
 * M5-WO6 §192 — the Targeting plans that the existing POST /api/rules/evaluate endpoint and Rules Inspector are
 * regression-tested with (apps/studio/tests/integration/m5-wo6-targeting-api.test.ts):
 *
 *   spellRadius    — Spell Radius at PER 5 / PRO 3: the WO2 BASE_RANGE step, the range Formula (75 ft) and the radius
 *                    Formula (15 ft) as separate M4 steps, with the listed base contribution (6 MP) in the outputs;
 *   maneuverRadius — Maneuver Radius at Martial EXPERT / STR 5: rank_base × str = 50 ft;
 *   multiTarget    — Multi-Target with an explicit count of 1: an INVALID result by an M4 Requirement.
 *
 * This test REGENERATES them from the canonical content and the real compiler and requires the committed fixture to be
 * identical (source maps included). Set M5_WO6_WRITE_FIXTURE=1 to rewrite it deliberately. No browser-side math.
 */
const ROOT = path.resolve(import.meta.dirname, "../../../..");
const FIXTURE = path.join(ROOT, "apps/studio/tests/integration/fixtures/m5-wo6-targeting-plans.json");
const uuid = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const RULESET = uuid(9811);
const MANIFEST = uuid(9812);
const KEYWORDS = KEYWORD_CONTENT.keywords.map((k, i) => ({ keywordId: uuid(9960 + i), canonicalKey: k.canonicalKey, categoryId: uuid(9959) }));

function bundle() {
  const identity = (i: number) => ({ entityId: uuid(11000 + i), entityVersionId: uuid(11500 + i) });
  const rules = TARGETING_DEFINITIONS.map((d, i) => ({ ...identity(i), canonicalKey: d.canonicalKey, entityType: PROWESS_DEFINITION_KINDS[d.definitionKind].entityTypes[0], sourceRulesetId: RULESET, sourceManifestId: MANIFEST }));
  const ruleset = createRulesetContext({ rulesetId: RULESET, manifestId: MANIFEST, rules });
  if (!ruleset.ok) throw new Error("ruleset");
  const definitions = TARGETING_DEFINITIONS.map((d, i) => ({
    schemaVersion: d.schemaVersion,
    systemFamily: PROWESS_DEFINITION_KINDS[d.definitionKind].family,
    definitionKind: d.definitionKind,
    ...identity(i),
    canonicalKey: d.canonicalKey,
    payload: d.payload,
    provenance: { rulesetId: RULESET, manifestId: MANIFEST, releaseId: null, sourceRulesetId: RULESET, sourceManifestId: MANIFEST, legacyTerms: [] },
  }));
  const out = createProwessDefinitionBundle({ ruleset: ruleset.value, definitions });
  if (!out.ok) throw new Error(JSON.stringify(out.problems));
  return { ruleset: ruleset.value, bundle: out.value };
}

function build() {
  const { ruleset, bundle: definitions } = bundle();
  const ref = (canonicalKey: string) => {
    const d = definitions.definitions.find((x) => x.canonicalKey === canonicalKey)!;
    return { entityId: d.entityId, entityVersionId: d.entityVersionId, canonicalKey: d.canonicalKey, definitionKind: d.definitionKind, systemFamily: d.systemFamily };
  };
  const compile = (subjectKey: string, composition: Record<string, unknown>, character: Record<string, unknown>) => {
    const plan = compileAbilityTargeting({ contractVersion: 1, subjectKey, composition, definitions, ruleset, character, keywords: KEYWORDS });
    if (!plan.ok) throw new Error(JSON.stringify(plan.problems));
    return plan.value;
  };
  const fixture = (evaluationKey: string, plan: ReturnType<typeof compile>) => ({ evaluationKey, plan: plan.evaluationPlan, outputs: plan.outputs, sourceMap: plan.sourceMap });
  return JSON.parse(
    JSON.stringify({
      note: "GENERATED by packages/prowess-db/tests/unit/m5-wo6-inspector-fixture.test.ts from the canonical Targeting content and @prowess/game — do not edit by hand.",
      spellRadius: fixture("m5-wo6.spell-radius", compile("inspector_spell_radius", spellWith(ref, "spell.targeting.radius"), characterOf({ PER: 5, PRO: 3 }))),
      maneuverRadius: fixture("m5-wo6.maneuver-radius", compile("inspector_maneuver_radius", maneuverWith(ref, "maneuver.targeting.radius", { originMode: "THROWN_IMPACT" }), characterOf({ STR: 5 }, "EXPERT"))),
      multiTarget: fixture("m5-wo6.multi-target", compile("inspector_multi_target", spellWith(ref, "spell.targeting.multi_target", { targetCount: 1 }), characterOf({ PER: 4, PRO: 4 }))),
    }),
  ) as Record<string, unknown>;
}

describe("M5-WO6 Rules Inspector / API fixture is exactly what @prowess/game compiles", () => {
  it("regenerates identically (deterministic compilation of canonical Targeting content)", () => {
    const fresh = build();
    if (process.env.M5_WO6_WRITE_FIXTURE === "1") writeFileSync(FIXTURE, `${JSON.stringify(fresh, null, 2)}\n`);
    expect(JSON.parse(readFileSync(FIXTURE, "utf8"))).toEqual(fresh);
    expect(build()).toEqual(fresh);
  });
});
