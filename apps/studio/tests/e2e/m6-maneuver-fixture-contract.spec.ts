import { expect, test, type Page, type Route } from "@playwright/test";
import { maneuverUiApi } from "./m6-wo8-ui-api";
import type { CharacterDto, CharacterSheetDto } from "../../app/characters/_lib/character-client";
import type { ManeuverDetailDto } from "../../app/characters/_lib/maneuver-types";

/** Node-only contract check; no browser fixture or PostgreSQL connection. The six browser scenarios remain separate. */
test("approved browser API fixtures execute the actual engine and preserve current revisions", async () => {
  let handler!: (route: Route) => Promise<unknown>;
  const page = { route: async (_match: unknown, callback: typeof handler) => { handler = callback; } } as unknown as Page;
  const api = await maneuverUiApi(page, "basic", true);
  const request = async (path: string, method = "GET", body: unknown = null) => {
    let status = 0, payload: Record<string, unknown> = {};
    await handler({ request: () => ({ method: () => method, url: () => `http://localhost/api/characters/character${path}`, postDataJSON: () => body }), fulfill: async (response: { status: number; body: string }) => { status = response.status; payload = JSON.parse(response.body); } } as unknown as Route);
    return { status, payload };
  };
  const call = (path: string, method = "GET", body: unknown = null) => request(`/maneuvers/maneuver${path}`, method, body);
  const character = (await request("")).payload.data as CharacterDto;
  expect(character).toMatchObject({ id: "character", name: "Maneuver Tester", status: "CORE_COMPLETE", release: { id: "release" }, resolution: { status: "READY" } });
  expect(typeof character.release.releaseNumber).toBe("number");
  expect(character.choices).toHaveProperty("ancestry");
  expect(character).not.toHaveProperty("maneuver");
  await expect(request("/unregistered")).rejects.toThrow("Unexpected fixture API request: GET");
  const loaded = await call("/builder"); expect(loaded.status).toBe(200);
  const validate = await call("/validate", "POST", { expectedVersion: api.version() });
  expect(JSON.stringify(validate.payload)).toContain('"state":"VALID"');
  const finalized = await call("/finalize", "POST", { expectedVersion: api.version() }); expect(finalized.status).toBe(200);
  const detail = (await call("")).payload.data as ManeuverDetailDto;
  expect(detail.signature.used).toBe(2);
  expect(detail.history).toHaveLength(1);
  expect(detail.maneuver.current?.revisionNumber).toBe(1);
  const original = structuredClone(detail.maneuver.current);
  await call("/rebuild", "POST", { expectedVersion: api.version() });
  expect(((await call("")).payload.data as ManeuverDetailDto).maneuver.current).toEqual(original);
  const rebuilt = structuredClone(api.draft()); rebuilt.concept.name = "Rebuilt Maneuver";
  const bad = structuredClone(api.draft()); bad.effects = []; bad.effectAttachments = [];
  await call("/draft", "PUT", { expectedVersion: api.version(), draft: bad });
  expect((await call("/finalize", "POST", { expectedVersion: api.version() })).status).toBe(422);
  expect(((await call("")).payload.data as ManeuverDetailDto).maneuver.current).toEqual(original);
  await call("/draft", "PUT", { expectedVersion: api.version(), draft: rebuilt });
  expect((await call("/finalize", "POST", { expectedVersion: api.version() })).status).toBe(200);
  const active = (await call("")).payload.data as ManeuverDetailDto;
  expect(active.maneuver.current?.revisionNumber).toBe(2);
  expect(active.history.map(r => [r.revisionNumber, r.current])).toEqual([[1, false], [2, true]]);
  expect(active.history[0]?.draft).toEqual(original?.draft);
  const sheet = (await request("/sheet")).payload.data as CharacterSheetDto;
  expect(sheet.identity).toMatchObject({ id: character.id, name: character.name });
  expect(sheet.signatureManeuvers).toHaveLength(1);
  expect(sheet.signatureManeuvers?.[0]).toMatchObject({ name: "Rebuilt Maneuver", revisionNumber: 2, finalApCost: active.maneuver.current?.evaluation?.cost?.ap.finalApCost });
  const abilities = (await request("/abilities")).payload.data as { signature: { used: number }; spells: unknown[] };
  expect(abilities.signature.used).toBe(2); expect(abilities.spells).toHaveLength(1);
  expect((await call("/retire", "POST", { expectedVersion: api.version() })).status).toBe(200);
  const retired = (await call("")).payload.data as ManeuverDetailDto;
  expect(retired.maneuver.status).toBe("RETIRED");
  expect(retired.history).toEqual(active.history);
  expect(retired.signature.used).toBe(1);
  expect(((await request("/sheet")).payload.data as CharacterSheetDto).signatureManeuvers).toEqual([]);
  expect(((await request("/abilities")).payload.data as typeof abilities).signature.used).toBe(1);
});
