/**
 * One-time generator of scripts/ci/legacy-inventory.json: everything the pre-CLOSEOUT-03 workflows executed, read from
 * git at the CLOSEOUT-03 baseline (default f3a5698b0b70968f63f82cfdd6bad8ddb335c20a), so the snapshot cannot be edited
 * by changing today's workflows.
 *
 *   node scripts/ci/snapshot-legacy-inventory.mjs [baseline-sha]
 *
 * Items: every vitest test file named in a step (`test-file`), every whole-suite run (`suite`), every control script
 * (`control-script`) and every other executed command line (`command`), each with its workflow / job / step.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const sha = process.argv[2] ?? "f3a5698b0b70968f63f82cfdd6bad8ddb335c20a";
const git = (args) => {
  const r = spawnSync("git", args, { cwd: root, encoding: "utf8" });
  if (r.status !== 0) throw new Error(r.stderr);
  return r.stdout;
};
const PKG = {
  "@prowess/model": "packages/prowess-model", "@prowess/ui": "packages/prowess-ui", "@prowess/import": "packages/prowess-import",
  "@prowess/rules": "packages/prowess-rules", "@prowess/game": "packages/prowess-game", "@prowess/db": "packages/prowess-db",
  "@prowess/test-fixtures": "packages/prowess-test-fixtures", "@prowess/studio": "apps/studio",
};
const SUITE = {
  "packages/prowess-model:test:unit": "model-unit", "packages/prowess-ui:test:unit": "ui-unit", "packages/prowess-import:test:unit": "import-unit",
  "packages/prowess-rules:test:unit": "rules-unit", "packages/prowess-game:test:unit": "game-unit", "packages/prowess-db:test:unit": "db-unit",
  "packages/prowess-test-fixtures:test:unit": "test-fixtures-unit", "apps/studio:test:unit": "studio-unit",
  "packages/prowess-db:test:integration": "db-integration", "apps/studio:test:integration": "studio-integration",
};
const workflows = git(["ls-tree", "--name-only", sha, ".github/workflows/"]).split("\n").filter((f) => f.endsWith(".yml"));
const items = [];
const namedGates = [];
for (const file of workflows) {
  const workflow = path.basename(file);
  const lines = git(["show", `${sha}:${file}`]).split("\n");
  let job = null, step = null, inRun = false, runIndent = 0;
  for (const raw of lines) {
    const jobMatch = /^ {2}([a-z0-9-]+):\s*$/.exec(raw);
    if (jobMatch) { job = jobMatch[1]; inRun = false; continue; }
    const stepMatch = /^\s+- name: (.+)$/.exec(raw);
    if (stepMatch) {
      step = stepMatch[1]; inRun = false;
      if (/audit|regression|gate/i.test(step)) namedGates.push(`${workflow}#${job}: ${step}`);
      continue;
    }
    const runMatch = /^(\s+)run: (.*)$/.exec(raw);
    let command = null;
    if (runMatch) { inRun = runMatch[2] === "|"; runIndent = runMatch[1].length; command = inRun ? null : runMatch[2]; }
    else if (inRun) {
      if (raw.trim() === "") continue;
      if (raw.length - raw.trimStart().length <= runIndent) { inRun = false; continue; }
      command = raw.trim();
    }
    if (command === null || step === null) continue;
    const at = { workflow, job, step };
    const vitest = /^pnpm --filter "(@prowess\/[a-z-]+)" exec vitest run (?:--config (\S+) )?(.+)$/.exec(command);
    const suiteRun = /^pnpm ((?:--filter "@prowess\/[a-z-]+" )+)run (test:unit|test:integration)$/.exec(command);
    const control = /^node (scripts\/[a-z0-9-]+-negative-controls\.mjs)$/.exec(command);
    if (vitest) {
      for (const f of vitest[3].split(/\s+/)) items.push({ ...at, type: "test-file", value: `${PKG[vitest[1]]}/${f}` });
    } else if (suiteRun) {
      for (const m of suiteRun[1].matchAll(/"(@prowess\/[a-z-]+)"/g)) items.push({ ...at, type: "suite", value: SUITE[`${PKG[m[1]]}:${suiteRun[2]}`] });
    } else if (control) {
      items.push({ ...at, type: "control-script", value: control[1] });
    } else if (/(^|\s)(pnpm|node|psql|\.\/node_modules\/\.bin\/prisma)\s/.test(command)) {
      items.push({ ...at, type: "command", value: command });
    }
  }
}
writeFileSync(path.join(root, "scripts/ci/legacy-inventory.json"), `${JSON.stringify({ $comment: `Frozen snapshot of every check the workflows ran at ${sha} (generated by scripts/ci/snapshot-legacy-inventory.mjs). Do not edit by hand.`, baseline: sha, workflows, namedGates, items }, null, 2)}\n`);
console.log(`${workflows.length} workflows, ${namedGates.length} named gate steps, ${items.length} items`);
