/**
 * The permanent gate inventory (M5-CLOSEOUT-03 §5) and its machine check.
 *
 * scripts/ci/gates.json is the single list of permanent protection: every suite the consolidated workflow runs (with
 * the job that runs it and where its authoritative report lands), every named gate (its test files, complete suites,
 * mutation / negative control script and exact control count, smoke checks, the job and the workflow it ran in
 * before), and every non-vitest check (Prisma, lint, architecture, typecheck, guarded reset, build, Playwright).
 *
 * scripts/ci/legacy-inventory.json is a frozen snapshot of everything the pre-CLOSEOUT-03 workflows executed
 * (ci.yml + the dedicated M5-WO7…WO13 workflows at f3a5698), generated by scripts/ci/snapshot-legacy-inventory.mjs.
 *
 * `checkInventory` returns every problem (empty = consistent). It proves:
 *   1. old unique assertion inventory ⊆ new consolidated inventory (every legacy test file, suite, control script and
 *      command is represented);
 *   2. every gate is a named step of its job in .github/workflows/ci.yml that verifies exactly its files and runs its
 *      controls with the exact inventory count;
 *   3. every suite is executed in its job and delivers its report; every check command is present in its job;
 *   4. every control script in scripts/ belongs to exactly one gate; every listed file exists.
 * Run by apps/studio/tests/unit/ci-gate-inventory.test.ts and by `node scripts/ci/gate-inventory.mjs`.
 */
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function loadInventory(root) {
  return JSON.parse(readFileSync(path.join(root, "scripts/ci/gates.json"), "utf8"));
}

/** The suite that owns a repository-relative test file. */
export function suiteOfFile(inventory, file) {
  const owners = Object.entries(inventory.suites).filter(([, s]) => file.startsWith(`${s.package}/${s.include.dir}/`) && s.include.suffixes.some((x) => file.endsWith(x)));
  if (owners.length !== 1) throw new Error(`${file} must belong to exactly one suite (found ${owners.map(([k]) => k).join(", ") || "none"})`);
  return owners[0][0];
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

/** Every test file of a suite on disk (repository-relative), from the suite's vitest include rule. */
export function suiteTestFiles(root, suite) {
  return walk(path.join(root, suite.package, suite.include.dir))
    .map((f) => path.relative(root, f).split(path.sep).join("/"))
    .filter((f) => suite.include.suffixes.some((x) => f.endsWith(x)))
    .sort();
}

/** `jobs:` blocks of a workflow, keyed by job id (2-space indented keys under `jobs:`). */
export function workflowJobs(text) {
  const start = text.indexOf("\njobs:\n");
  if (start === -1) return {};
  const body = text.slice(start + 7);
  const jobs = {};
  const re = /^ {2}([a-z0-9-]+):\s*$/gm;
  const marks = [...body.matchAll(re)].map((m) => ({ id: m[1], at: m.index }));
  marks.forEach((m, i) => { jobs[m.id] = body.slice(m.at, i + 1 < marks.length ? marks[i + 1].at : undefined); });
  return jobs;
}

/** The text of one named step (from its `- name:` line to the next step) inside a job block. */
export function stepText(job, name) {
  const marker = `- name: ${name}\n`;
  const at = job.indexOf(marker);
  if (at === -1) return null;
  const next = job.indexOf("\n      - name:", at + marker.length);
  return job.slice(at, next === -1 ? undefined : next);
}

export function checkInventory(root) {
  const problems = [];
  const fail = (m) => problems.push(m);
  const inventory = loadInventory(root);
  const ci = readFileSync(path.join(root, ".github/workflows/ci.yml"), "utf8");
  const jobs = workflowJobs(ci);
  const ids = new Set();
  const gateFiles = new Set();
  const controlScripts = new Map();

  for (const [id, suite] of Object.entries(inventory.suites)) {
    const job = jobs[suite.job];
    if (!job) { fail(`suite ${id}: job ${suite.job} is not in ci.yml`); continue; }
    const collects = job.split("\n").some((l) => /node scripts\/ci\/collect-reports\.mjs /.test(l) && l.split("collect-reports.mjs ")[1].trim().split(/\s+/).includes(id));
    if (!collects) fail(`suite ${id}: job ${suite.job} does not collect its authoritative report`);
    if (!job.includes(suite.report.split("/").pop())) fail(`suite ${id}: job ${suite.job} does not write ${suite.report}`);
    if (suiteTestFiles(root, suite).length === 0) fail(`suite ${id}: no test files under ${suite.package}/${suite.include.dir}`);
  }

  for (const gate of inventory.gates) {
    if (ids.has(gate.id)) fail(`duplicate gate id ${gate.id}`);
    ids.add(gate.id);
    if (!gate.tiers.includes(2) || !gate.tiers.includes(3)) fail(`${gate.id}: every permanent gate belongs to Tier 2 and Tier 3`);
    const job = jobs[gate.job];
    if (!job) { fail(`${gate.id}: job ${gate.job} is not in ci.yml`); continue; }
    const step = stepText(job, gate.name);
    if (step === null) { fail(`${gate.id}: no step named "${gate.name}" in job ${gate.job}`); continue; }
    if (!step.includes(`node scripts/ci/verify-gate.mjs ${gate.id} `)) fail(`${gate.id}: its step does not verify the gate from the authoritative reports`);
    for (const file of gate.tests) {
      gateFiles.add(file);
      if (!existsSync(path.join(root, file))) fail(`${gate.id}: ${file} does not exist`);
      if (!step.includes(` ${file}`)) fail(`${gate.id}: its step does not list ${file}`);
      try { suiteOfFile(inventory, file); } catch (e) { fail(`${gate.id}: ${e.message}`); }
    }
    for (const suite of gate.allOf) if (!inventory.suites[suite]) fail(`${gate.id}: unknown suite ${suite}`);
    if (gate.controls) {
      const { script, count } = gate.controls;
      if (!existsSync(path.join(root, script))) fail(`${gate.id}: ${script} does not exist`);
      if (!step.includes(`PROWESS_EXPECT_CONTROLS=${count} node ${script}`)) fail(`${gate.id}: its step does not run ${script} with the exact control count ${count}`);
      if (controlScripts.has(script)) fail(`${script} is owned by both ${controlScripts.get(script)} and ${gate.id}`);
      controlScripts.set(script, gate.id);
    }
    for (const smoke of gate.smoke) {
      const check = inventory.checks.find((c) => c.id === smoke.toUpperCase());
      if (!check) fail(`${gate.id}: unknown smoke check ${smoke}`);
      else if (!step.includes(check.command)) fail(`${gate.id}: its step does not run the ${smoke} smoke check`);
    }
  }
  for (const name of readdirSync(path.join(root, "scripts")).filter((f) => f.endsWith("-negative-controls.mjs"))) {
    if (!controlScripts.has(`scripts/${name}`)) fail(`scripts/${name} belongs to no gate`);
  }
  for (const check of inventory.checks) {
    const job = jobs[check.job];
    if (!job) fail(`check ${check.id}: job ${check.job} is not in ci.yml`);
    else if (!job.includes(check.command)) fail(`check ${check.id}: "${check.command}" is not run in job ${check.job}`);
  }

  // Old ⊆ new.
  const legacy = JSON.parse(readFileSync(path.join(root, "scripts/ci/legacy-inventory.json"), "utf8"));
  const retired = inventory.retired ?? [];
  for (const r of retired) if (!r.reason) fail(`retired ${r.type} ${r.value}: a retirement needs its reason`);
  for (const item of legacy.items) {
    const where = `${item.workflow}#${item.job} "${item.step}"`;
    if (retired.some((r) => r.type === item.type && r.value === item.value)) continue;
    if (item.type === "test-file") {
      if (!gateFiles.has(item.value)) {
        let suite = null;
        try { suite = suiteOfFile(inventory, item.value); } catch { /* reported below */ }
        if (suite === null || !gate_allOf_covers(inventory, suite)) fail(`legacy ${where}: ${item.value} is no longer verified by any gate`);
      }
    } else if (item.type === "suite") {
      if (!inventory.suites[item.value]) fail(`legacy ${where}: suite ${item.value} is no longer run`);
    } else if (item.type === "control-script") {
      if (!controlScripts.has(item.value)) fail(`legacy ${where}: ${item.value} is no longer run`);
    } else if (item.type === "command") {
      if (!inventory.checks.some((c) => c.command === item.value) && !ci.includes(item.value)) fail(`legacy ${where}: command no longer run: ${item.value}`);
    } else fail(`legacy ${where}: unknown item type ${item.type}`);
  }
  for (const gate of legacy.namedGates) {
    if (!inventory.gates.some((g) => g.previous.includes(gate))) fail(`legacy named gate ${gate} has no replacement gate`);
  }
  return problems;
}

function gate_allOf_covers(inventory, suite) {
  return inventory.gates.some((g) => g.allOf.includes(suite));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const problems = checkInventory(root);
  if (problems.length) {
    console.error(problems.map((p) => `✗ ${p}`).join("\n"));
    process.exit(1);
  }
  const inventory = loadInventory(root);
  const controls = inventory.gates.reduce((n, g) => n + (g.controls?.count ?? 0), 0);
  console.log(`Gate inventory consistent: ${Object.keys(inventory.suites).length} suites, ${inventory.gates.length} gates, ${controls} controls, ${inventory.checks.length} checks; every legacy item represented.`);
}
